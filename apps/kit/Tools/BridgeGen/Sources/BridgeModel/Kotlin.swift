import Foundation

/// Writes the Kotlin kit-core reads and writes bridged values with: a data
/// class per struct, an enum class per `String` enum, and a sealed interface
/// per payload enum whose serializer reads and writes Swift's synthesized
/// shape (`{"case": {"label": …}}`, `{"case": {}}` with no payload).
public enum Kotlin {
    static let hardKeywords: Set<String> = [
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
        "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when",
        "while",
    ]

    /// - Parameter uses: the packages another configuration generated the
    ///   model's external declarations into; with any, the file imports them
    ///   and their shared serializers rather than declaring its own.
    public static func write(_ model: Model, package: String, fingerprint: String, generatedBy: String, uses: [String] = []) throws -> String {
        let names = Names(package: package, external: Set(model.declarations.filter(\.external).map(\.name)), usedPackage: uses.first)
        let model = model.own
        try check(model)
        if !uses.isEmpty {
            return try dependent(model, package: package, fingerprint: fingerprint, generatedBy: generatedBy, uses: uses, names: names)
        }
        var out = """
            // Generated by `\(generatedBy)` from bridge.golden.json; do not edit.
            @file:Suppress("ktlint", "unused", "ClassName", "EnumEntryName", "PropertyName", "RedundantVisibilityModifier")

            package \(package)

            import kotlin.reflect.KClass
            import kotlinx.serialization.ExperimentalSerializationApi
            import kotlinx.serialization.KSerializer
            import kotlinx.serialization.SerialName
            import kotlinx.serialization.Serializable
            import kotlinx.serialization.SerializationException
            import kotlinx.serialization.descriptors.SerialDescriptor
            import kotlinx.serialization.descriptors.buildClassSerialDescriptor
            import kotlinx.serialization.encoding.Decoder
            import kotlinx.serialization.encoding.Encoder
            import kotlinx.serialization.json.Json
            import kotlinx.serialization.json.JsonArray
            import kotlinx.serialization.json.JsonDecoder
            import kotlinx.serialization.json.JsonElement
            import kotlinx.serialization.json.JsonEncoder
            import kotlinx.serialization.json.JsonNull
            import kotlinx.serialization.json.JsonObject
            import kotlinx.serialization.json.JsonPrimitive
            import kotlinx.serialization.json.JsonUnquotedLiteral
            import kotlinx.serialization.json.booleanOrNull
            import kotlinx.serialization.json.buildJsonObject

            /** The SHA-256 of bridge.golden.json, which `start` holds equal to the Swift library's. */
            public object ProtocolFingerprint {
                public const val VALUE: String = "\(fingerprint)"
            }

            /**
             * The JSON bridged values cross in. A Swift optional that is nil is left
             * out, and one Kotlin leaves out or sends as null reads as nil; a key
             * neither side declares is refused, since both were built from one golden.
             */
            public val BridgeJson: Json = Json {
                explicitNulls = false
                encodeDefaults = true
            }

            /**
             * Any JSON (Swift's `JSONValue`), with every number written again as the
             * digits it was read with: kotlinx writes a number back through Long or
             * Double, which drops the digits a decimal or a large integer has past them.
             */
            public object ExactJson : KSerializer<JsonElement> {
                override val descriptor: SerialDescriptor = JsonElement.serializer().descriptor

                override fun deserialize(decoder: Decoder): JsonElement {
                    val json = decoder as? JsonDecoder ?: throw SerializationException("JSON crosses as JSON only")
                    return exact(json.decodeJsonElement())
                }

                override fun serialize(encoder: Encoder, value: JsonElement) {
                    val json = encoder as? JsonEncoder ?: throw SerializationException("JSON crosses as JSON only")
                    json.encodeJsonElement(exact(value))
                }

                @OptIn(ExperimentalSerializationApi::class)
                public fun exact(element: JsonElement): JsonElement = when (element) {
                    is JsonNull -> element
                    is JsonPrimitive -> if (element.isString || element.booleanOrNull != null) element else JsonUnquotedLiteral(element.content)
                    is JsonObject -> JsonObject(element.mapValues { exact(it.value) })
                    is JsonArray -> JsonArray(element.map(::exact))
                }
            }

            /**
             * SubstrateRuntime's `KeyedList`: its rows and the revision they are at.
             * A presentation crosses with each one as a reference to the list sent
             * apart, and `KeyedListTree` puts the rows back before it is decoded.
             */
            @Serializable
            public data class KeyedList<Row>(
                val revision: Long,
                val rows: List<Row>,
            )

            /** Swift's synthesized enum coding: an object of one key, the case, holding its payload. */
            public class SwiftEnumSerializer<T : Any>(
                private val serialName: String,
                private val cases: List<Case<T>>,
            ) : KSerializer<T> {
                public class Case<T : Any>(public val name: String, public val type: KClass<out T>, public val serializer: KSerializer<out T>)

                override val descriptor: SerialDescriptor = buildClassSerialDescriptor(serialName)

                override fun serialize(encoder: Encoder, value: T) {
                    val json = encoder as? JsonEncoder ?: throw SerializationException("$serialName crosses as JSON only")
                    val case = cases.firstOrNull { it.type.isInstance(value) }
                        ?: throw SerializationException("$serialName has no case for ${value::class}")
                    @Suppress("UNCHECKED_CAST")
                    val payload = json.json.encodeToJsonElement(case.serializer as KSerializer<T>, value)
                    json.encodeJsonElement(buildJsonObject { put(case.name, payload) })
                }

                override fun deserialize(decoder: Decoder): T {
                    val json = decoder as? JsonDecoder ?: throw SerializationException("$serialName crosses as JSON only")
                    val element = json.decodeJsonElement() as? JsonObject
                        ?: throw SerializationException("$serialName is not an object")
                    if (element.size != 1) throw SerializationException("$serialName has ${element.size} keys, and a case is one")
                    val (name, payload) = element.entries.first()
                    val case = cases.firstOrNull { it.name == name } ?: throw SerializationException("$serialName has no case $name")
                    return json.json.decodeFromJsonElement(case.serializer, payload)
                }
            }


            """
        out += scope(nil, model: model, indent: "", names: names)
        out += serializers(model)
        return out
    }

    /// Where a type is spelled: which package each declaration is in, and
    /// the names a nested class takes over in the scope being written (a
    /// case class `AccessBanner` inside `FixturePresentation`), where a type
    /// of that name is written with its package so it means the top-level one.
    struct Names {
        var package: String
        var external: Set<String>
        var usedPackage: String?
        var shadowed: Set<String> = []

        func qualified(_ name: String) -> String {
            let first = name.split(separator: ".").first.map(String.init) ?? name
            guard shadowed.contains(first) else { return path(name) }
            return "\(external.contains(name) ? usedPackage ?? package : package).\(path(name))"
        }

        func entering(_ declaration: Declaration, model: Model) -> Names {
            var next = self
            next.shadowed.formUnion(declaration.cases.filter { !$0.fields.isEmpty || declaration.kind == .enum }.map { caseClass($0.name) })
            if declaration.kind == .stringEnum { next.shadowed.subtract(declaration.cases.map { caseClass($0.name) }) }
            next.shadowed.formUnion(model.children(of: declaration.name).map(\.simpleName))
            next.shadowed.formUnion(model.namespaces(in: declaration.name).map { $0.split(separator: ".").last.map(String.init) ?? $0 })
            return next
        }
    }

    /// The values of a configuration that `uses` another: its own declarations
    /// over the other's, whose package it imports whole.
    private static func dependent(
        _ model: Model, package: String, fingerprint: String, generatedBy: String, uses: [String],
        names: Names
    ) throws -> String {
        var out = """
            // Generated by `\(generatedBy)` from its bridge golden; do not edit.
            @file:Suppress("ktlint", "unused", "ClassName", "EnumEntryName", "PropertyName", "RedundantVisibilityModifier")

            package \(package)

            \(uses.map { "import \($0).*" }.joined(separator: "\n"))
            import kotlinx.serialization.KSerializer
            import kotlinx.serialization.SerialName
            import kotlinx.serialization.Serializable
            import kotlinx.serialization.json.JsonElement

            /** The SHA-256 of this configuration's golden. */
            public object ProtocolFingerprint {
                public const val VALUE: String = "\(fingerprint)"
            }


            """
        out += scope(nil, model: model, indent: "", names: names)
        out += serializers(model)
        return out
    }

    /// The map the round trip looks each value's serializer up in; a generic
    /// one takes its arguments' serializers, so it is not in it.
    private static func serializers(_ model: Model) -> String {
        var out = "/** Every bridged value's serializer by its Swift name, for the round-trip fixtures. */\n"
        out += "public val bridgedSerializers: Map<String, KSerializer<*>> = mapOf(\n"
        for declaration in model.declarations where !declaration.external && declaration.parameters.isEmpty {
            out += "    \"\(declaration.name)\" to \(serializer(declaration)),\n"
        }
        out += ")\n"
        return out
    }

    private static func serializer(_ declaration: Declaration) -> String {
        let name = path(declaration.name)
        switch declaration.kind {
        case .enum: return "\(name).Serializer"
        case .struct, .stringEnum: return "\(name).serializer()"
        }
    }

    /// Kotlin refuses, or would silently change, what Swift allows here.
    static func check(_ model: Model) throws {
        var errors: [String] = []
        for declaration in model.declarations where declaration.kind == .enum {
            let classes = declaration.cases.map { caseClass($0.name) }
            let nested = Set(
                model.children(of: declaration.name).map(\.simpleName)
                    + model.namespaces(in: declaration.name).map { $0.split(separator: ".").last.map(String.init) ?? $0 })
            for (name, item) in zip(classes, declaration.cases) {
                if nested.contains(name) || name == "Serializer" {
                    errors.append("\(declaration.name).\(item.name) would be the Kotlin class \(name), which another name there takes")
                }
            }
            if Set(classes).count != classes.count { errors.append("\(declaration.name) has two cases that differ only in their first letter's case") }
        }
        if !errors.isEmpty { throw ModelError(location: "kotlin", message: errors.joined(separator: "; ")) }
    }

    static func caseClass(_ name: String) -> String {
        name.prefix(1).uppercased() + name.dropFirst()
    }

    static func identifier(_ name: String) -> String {
        hardKeywords.contains(name) ? "`\(name)`" : name
    }

    static func path(_ swiftName: String) -> String {
        swiftName.split(separator: ".").map { identifier(String($0)) }.joined(separator: ".")
    }

    static func type(_ type: BridgedType, names: Names? = nil) -> String {
        func spell(_ name: String) -> String { names?.qualified(name) ?? path(name) }
        func again(_ type: BridgedType) -> String { Self.type(type, names: names) }
        return switch type {
        case .string: "String"
        case .bool: "Boolean"
        case .int: "Long"
        case .double: "Double"
        case .json, .opaque: "@Serializable(with = ExactJson::class) JsonElement"
        case .date, .url, .uuid: "String"
        case let .named(name): spell(name)
        case let .generic(name, arguments): "\(spell(name))<\(arguments.map(again).joined(separator: ", "))>"
        case let .parameter(name): identifier(name)
        case let .keyedList(row): "KeyedList<\(again(row))>"
        case let .optional(wrapped): "\(again(wrapped))?"
        case let .array(element): "List<\(again(element))>"
        case let .dictionary(value): "Map<String, \(again(value))>"
        }
    }

    private static func parameters(_ fields: [Field], indent: String, names: Names) -> String {
        let unlabelled = fields.filter(\.isUnlabelled)
        let labels = Set(fields.filter { !$0.isUnlabelled }.map(\.name))
        return fields.map { field in
            let optional = if case .optional = field.type { " = null" } else { "" }
            guard field.isUnlabelled else { return "\(indent)    val \(identifier(field.name)): \(type(field.type, names: names))\(optional),\n" }
            // Swift keys an unlabelled value by its place; Kotlin names it `value`.
            let name = unlabelled.count == 1 && !labels.contains("value") ? "value" : "value\(field.name.dropFirst())"
            return "\(indent)    @SerialName(\(Golden.quote(field.name))) val \(name): \(type(field.type, names: names))\(optional),\n"
        }.joined()
    }

    /// `<Action>` after a generic struct's name.
    private static func typeParameters(_ declaration: Declaration) -> String {
        declaration.parameters.isEmpty ? "" : "<\(declaration.parameters.map(identifier).joined(separator: ", "))>"
    }

    /// The declarations and namespaces directly under `name`, each followed
    /// by a blank line.
    private static func scope(_ name: String?, model: Model, indent: String, names: Names) -> String {
        var out = ""
        for declaration in model.children(of: name) where !declaration.external {
            out += declare(declaration, model: model, indent: indent, names: names) + "\n"
        }
        for namespace in model.namespaces(in: name) {
            let simple = namespace.split(separator: ".").last.map(String.init) ?? namespace
            var inner = names
            inner.shadowed.formUnion(model.children(of: namespace).map(\.simpleName))
            out += "\(indent)public object \(identifier(simple)) {\n"
            out += scope(namespace, model: model, indent: indent + "    ", names: inner).dropLast()
            out += "\(indent)}\n\n"
        }
        return out
    }

    private static func declare(_ declaration: Declaration, model: Model, indent: String, names outer: Names) -> String {
        let name = identifier(declaration.simpleName)
        let names = outer.entering(declaration, model: model)
        var body = ""
        let inner = scope(declaration.name, model: model, indent: indent + "    ", names: names)
        if !inner.isEmpty { body = "\n" + inner.dropLast() }
        var out = ""
        switch declaration.kind {
        case .struct:
            out += "\(indent)@Serializable\n"
            if declaration.fields.isEmpty {
                out += "\(indent)public data object \(name)"
            } else {
                out +=
                    "\(indent)public data class \(name)\(typeParameters(declaration))(\n\(parameters(declaration.fields, indent: indent, names: names))\(indent))"
            }
            out += body.isEmpty ? "\n" : " {\(body)\(indent)}\n"
        case .stringEnum:
            out += "\(indent)@Serializable\n\(indent)public enum class \(name) {\n"
            for item in declaration.cases {
                out += "\(indent)    @SerialName(\(Golden.quote(item.rawValue ?? item.name))) \(identifier(item.name)),\n"
            }
            if !body.isEmpty { out += "\(indent)    ;\n\(body)" }
            out += "\(indent)}\n"
        case .enum:
            out += "\(indent)@Serializable(with = \(path(declaration.name)).Serializer::class)\n"
            out += "\(indent)public sealed interface \(name) {\n"
            for item in declaration.cases {
                let caseName = caseClass(item.name)
                out += "\(indent)    @Serializable\n"
                if item.fields.isEmpty {
                    out += "\(indent)    public data object \(caseName) : \(name)\n\n"
                } else {
                    out +=
                        "\(indent)    public data class \(caseName)(\n\(parameters(item.fields, indent: indent + "    ", names: names))\(indent)    ) : \(name)\n\n"
                }
            }
            out += "\(indent)    public object Serializer : KSerializer<\(path(declaration.name))> by SwiftEnumSerializer(\n"
            out += "\(indent)        \(Golden.quote(declaration.name)),\n"
            out += "\(indent)        listOf(\n"
            for item in declaration.cases {
                let caseName = caseClass(item.name)
                out += "\(indent)            SwiftEnumSerializer.Case(\(Golden.quote(item.name)), \(caseName)::class, \(caseName).serializer()),\n"
            }
            out += "\(indent)        ),\n\(indent)    )\n"
            out += body
            out += "\(indent)}\n"
        }
        return out
    }
}
