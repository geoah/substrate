import Foundation

/// What `bridge.json` names: the sources to read and the three files written
/// from them, each path relative to the repository's root.
public struct Configuration: Codable, Sendable {
    /// Target source folders; a folder's name is its module's.
    public var sources: [String]
    public var golden: String
    public var kotlin: String
    public var kotlinPackage: String
    public var swiftFingerprint: String
    /// Types outside the model a bridged value may carry as their own JSON,
    /// which Kotlin holds and never reads (a probe's whole answer).
    public var opaque: [String]?
    /// Other configurations whose declarations this one's name, by path:
    /// read with these sources, generated by those.
    public var uses: [String]?
}

/// The files a configuration generates, by path, and their content.
public struct Generation {
    public var files: [(path: String, content: String)]
    public var fingerprint: String

    public static let command = "mise run android:generate"

    public static func run(_ configuration: Configuration, root: URL) throws -> Generation {
        var used: [Configuration] = []
        for path in configuration.uses ?? [] {
            used.append(try JSONDecoder().decode(Configuration.self, from: Data(contentsOf: root.appendingPathComponent(path))))
        }
        var reader = Reader(opaque: Set((configuration.opaque ?? []) + used.flatMap { $0.opaque ?? [] }))
        let manager = FileManager.default
        func read(_ sources: [String], external: Bool) throws {
            for source in sources {
                let folder = root.appendingPathComponent(source)
                guard let walker = manager.enumerator(at: folder, includingPropertiesForKeys: nil) else {
                    throw ModelError(location: source, message: "not a folder")
                }
                let files = walker.compactMap { $0 as? URL }.filter { $0.pathExtension == "swift" }
                    .sorted { $0.path < $1.path }
                for file in files {
                    let relative = source + "/" + file.path.dropFirst(folder.path.count + 1)
                    reader.read(source: try String(contentsOf: file, encoding: .utf8), module: folder.lastPathComponent, path: relative,
                                external: external)
                }
            }
        }
        for other in used { try read(other.sources, external: true) }
        try read(configuration.sources, external: false)
        guard let model = reader.model() else {
            throw ModelError(location: "bridge", message: "\n" + reader.errors.map(\.description).joined(separator: "\n"))
        }
        let golden = Golden.write(model.own)
        let fingerprint = Golden.fingerprint(golden)
        let kotlin = try Kotlin.write(model, package: configuration.kotlinPackage, fingerprint: fingerprint, generatedBy: command,
                                      uses: used.map(\.kotlinPackage))
        let swift = """
        // Generated by `\(command)` from bridge.golden.json; do not edit.

        /// The SHA-256 of bridge.golden.json: the Kotlin kit-core was generated
        /// from must be what this library was built from, which `start` checks.
        public enum ProtocolFingerprint {
            public static let value = "\(fingerprint)"
        }

        """
        return Generation(files: [(configuration.golden, golden), (configuration.kotlin, kotlin), (configuration.swiftFingerprint, swift)],
                          fingerprint: fingerprint)
    }

    /// The paths whose content on disk is not what was generated.
    public func stale(root: URL) -> [String] {
        files.filter { file in
            (try? String(contentsOf: root.appendingPathComponent(file.path), encoding: .utf8)) != file.content
        }.map(\.path)
    }

    public func write(root: URL) throws {
        for file in files {
            let url = root.appendingPathComponent(file.path)
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try file.content.write(to: url, atomically: true, encoding: .utf8)
        }
    }
}
