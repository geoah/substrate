import Foundation
import SubstrateCore
import SubstrateScreens
import SubstrateUI
import Testing

/// SubstrateUI's design tokens written as Kotlin for kit-ui (§7.4), the
/// golden pattern the bridge's generator follows: the file in the tree is
/// what the tokens are today, and SUBSTRATE_UPDATE_FIXTURES=1 writes it
/// again after a change to one.
@Suite("The design tokens as Kotlin", .timeLimit(.minutes(10)))
struct DesignTokensKotlinTests {
    static let file = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
        .appendingPathComponent("../../android/kit-ui/src/main/kotlin/dev/reamde/substrate/kit/ui/KitTokens.kt").standardizedFileURL

    @Test func kitUIsTokensAreSubstrateUIs() throws {
        let text = Self.kotlin()
        if ProcessInfo.processInfo.environment["SUBSTRATE_UPDATE_FIXTURES"] == "1" {
            try FileManager.default.createDirectory(at: Self.file.deletingLastPathComponent(), withIntermediateDirectories: true)
            try text.write(to: Self.file, atomically: true, encoding: .utf8)
        }
        let onDisk = try String(contentsOf: Self.file, encoding: .utf8)
        #expect(onDisk == text, "stale: run `SUBSTRATE_UPDATE_FIXTURES=1 swift test --filter DesignTokensKotlinTests`")
    }

    @Test func everyKindGlyphHasAMaterialSymbol() {
        let kinds = ["a.example.com/x/task", "a.example.com/x/project", "a.example.com/x/person", "a.example.com/x/contact",
                     "a.example.com/x/organization", "a.example.com/x/team", "a.example.com/x/note", "a.example.com/x/calendar",
                     "a.example.com/x/series", "a.example.com/x/email", "a.example.com/x/message", "a.example.com/x/recipe",
                     "a.example.com/x/trip", "a.example.com/x/label", "a.example.com/x/account", "a.example.com/x/log",
                     "a.example.com/x/agent", "a.example.com/x/scratchpad", "a.example.com/x/widget"]
        for kind in kinds {
            #expect(DesignTokens.kindSymbols[KindGlyphSpec(kind: kind).symbol] != nil, "\(kind)")
        }
    }

    static func colour(_ value: UInt32) -> String { String(format: "Color(0xFF%06X)", value) }

    static func icon(_ material: String) -> String {
        material.hasPrefix("AutoMirrored.") ? "Icons.AutoMirrored.Rounded.\(material.dropFirst("AutoMirrored.".count))" : "Icons.Rounded.\(material)"
    }

    static func colours(_ colour: DesignTokens.Colour) -> String {
        "if (dark) \(Self.colour(colour.dark)) else \(Self.colour(colour.light))"
    }

    static func kotlin() -> String {
        var out = """
        // Generated by SubstrateKitTests' DesignTokensKotlinTests from SubstrateUI's DesignTokens; do not edit.
        // `SUBSTRATE_UPDATE_FIXTURES=1 swift test --package-path apps/kit --filter DesignTokensKotlinTests` writes it again.
        @file:Suppress("ktlint", "EnumEntryName", "unused")

        package dev.reamde.substrate.kit.ui

        import androidx.compose.material.icons.Icons
        import androidx.compose.material.icons.automirrored.rounded.*
        import androidx.compose.material.icons.rounded.*
        import androidx.compose.material3.MaterialTheme
        import androidx.compose.runtime.Composable
        import androidx.compose.runtime.ReadOnlyComposable
        import androidx.compose.ui.graphics.Color
        import androidx.compose.ui.graphics.vector.ImageVector
        import androidx.compose.ui.text.TextStyle
        import androidx.compose.ui.text.font.FontWeight
        import androidx.compose.ui.unit.Dp
        import androidx.compose.ui.unit.dp
        import dev.reamde.substrate.kit.bridge.ScreenSymbol
        import dev.reamde.substrate.kit.bridge.ScreenTone

        /** A tone's colour, as SubstrateUI's tokens give it: Apple's system colour's value, light and dark. */
        public fun ScreenTone.color(dark: Boolean): Color = when (this) {

        """
        for tone in ScreenTone.allCases {
            out += "    ScreenTone.\(tone.rawValue) -> \(colours(DesignTokens.tone(tone)))\n"
        }
        out += "}\n\n/** The console's kind hues. */\npublic enum class KindHue { \(KindHue.allCases.map(\.rawValue).joined(separator: ", ")) }\n\n"
        out += "public fun KindHue.color(dark: Boolean): Color = when (this) {\n"
        for hue in KindHue.allCases {
            out += "    KindHue.\(hue.rawValue) -> \(colours(DesignTokens.hue(hue)))\n"
        }
        out += "}\n\n/** A screen's mark as a Material Symbol; SwiftUI draws the SF Symbol named beside it. */\n"
        out += "public val ScreenSymbol.icon: ImageVector\n    get() = when (this) {\n"
        for symbol in ScreenSymbol.allCases {
            let glyph = DesignTokens.symbol(symbol)
            out += "        ScreenSymbol.\(symbol.rawValue) -> \(icon(glyph.material)) // \(glyph.sfSymbol)\n"
        }
        out += "    }\n\n/** A mark by the name a presentation gives it (`AppMenuSection.symbol`). */\n"
        out += "public fun menuIcon(name: String): ImageVector = when (name) {\n"
        for (name, glyph) in DesignTokens.menuSymbols.sorted(by: { $0.key < $1.key }) {
            out += "    \"\(name)\" -> \(icon(glyph.material)) // \(glyph.sfSymbol)\n"
        }
        out += "    else -> \(icon(DesignTokens.fallback.material)) // \(DesignTokens.fallback.sfSymbol)\n"
        out += "}\n\n/** The marks controls draw beside their words. */\npublic enum class KitMark(public val icon: ImageVector) {\n"
        for control in DesignTokens.Control.allCases {
            let glyph = DesignTokens.control(control)
            out += "    \(control.rawValue)(\(icon(glyph.material))), // \(glyph.sfSymbol)\n"
        }
        out += "}\n\n/** A kind's glyph, by the SF Symbol `KindGlyphSpec` names, as its Material Symbol. */\n"
        out += "public fun kindIcon(sfSymbol: String): ImageVector = when (sfSymbol) {\n"
        for (sf, material) in DesignTokens.kindSymbols.sorted(by: { $0.key < $1.key }) {
            out += "    \"\(sf)\" -> \(icon(material))\n"
        }
        out += "    else -> \(icon(DesignTokens.kindSymbols["shippingbox"]!))\n}\n\n"
        out += "/** What a run of text is on a screen, set in Material 3's type scale. */\npublic enum class KitText { \(DesignTokens.TextRole.allCases.map(\.rawValue).joined(separator: ", ")) }\n\n"
        out += "public val KitText.style: TextStyle\n    @Composable @ReadOnlyComposable\n    get() = when (this) {\n"
        for role in DesignTokens.TextRole.allCases {
            let style = DesignTokens.text(role)
            let weight = style.materialWeight.map { ".copy(fontWeight = FontWeight.\($0))" } ?? ""
            out += "        KitText.\(role.rawValue) -> MaterialTheme.typography.\(style.material)\(weight) // .\(style.apple), \(style.appleWeight)\n"
        }
        out += "    }\n\n/** Space between things, in dp as SwiftUI's are in points. */\npublic object KitSpacing {\n"
        for spacing in DesignTokens.Spacing.allCases {
            out += "    public val \(spacing): Dp = \(spacing.rawValue).dp\n"
        }
        out += "}\n\npublic object KitRadius {\n"
        for radius in DesignTokens.Radius.allCases {
            out += "    public val \(radius): Dp = \(radius.rawValue).dp\n"
        }
        out += "}\n"
        return out
    }
}
