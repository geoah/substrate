"""Write the body map's shapes, front and back, as Swift path data.

The shapes are react-native-body-highlighter's male front and back figures
(MIT, Copyright (c) 2022 ELABBASSI Hicham), read at the commit pinned below.
Their SVG paths use relative arcs and quadratics; this script makes each one
absolute moves, lines and cubic curves only, so the app's reader is a few
lines, and moves the back figure's viewBox (724..1448) onto the front's
(0..724), so both are drawn in one 724 x 1448 box.

    uv run --with svgelements apps/apple/scripts/body-map.py
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

from svgelements import Arc, Close, CubicBezier, Line, Move, Path as SVGPath, QuadraticBezier

APPLE = Path(__file__).resolve().parents[1]
OUT = APPLE / "SubstrateWorkouts/Sources/Views/Stats/BodyMapShapes.swift"
REPOSITORY = "HichamELBSI/react-native-body-highlighter"
COMMIT = "8ed39ac2ae9cb46fb79d77eedec7e5b029a75174"
LICENSE = "MIT License, Copyright (c) 2022 ELABBASSI Hicham"
WIDTH = 724


def fetch(name: str) -> str:
    url = f"https://raw.githubusercontent.com/{REPOSITORY}/{COMMIT}/assets/{name}.ts"
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def parts(source: str) -> dict[str, list[str]]:
    """Each slug's path strings, its common, left and right paths together."""
    out: dict[str, list[str]] = {}
    for block in re.split(r"\n  \{", source)[1:]:
        slug = re.search(r'slug: "([a-z-]+)"', block)
        if slug:
            out.setdefault(slug.group(1), []).extend(re.findall(r'"(M[^"]+)"', block))
    return out


def number(value: float) -> str:
    text = f"{value:.1f}"
    return text[:-2] if text.endswith(".0") else text


def absolute(d: str, shift: float) -> str:
    out = []
    for segment in SVGPath(d).segments():
        if isinstance(segment, Move):
            out.append(f"M{number(segment.end.x - shift)} {number(segment.end.y)}")
        elif isinstance(segment, Close):
            out.append("Z")
        elif isinstance(segment, Line):
            out.append(f"L{number(segment.end.x - shift)} {number(segment.end.y)}")
        elif isinstance(segment, (CubicBezier, QuadraticBezier, Arc)):
            curves = [segment] if isinstance(segment, CubicBezier) else (
                [CubicBezier(segment.start, segment.start + (segment.control - segment.start) * (2 / 3),
                             segment.end + (segment.control - segment.end) * (2 / 3), segment.end)]
                if isinstance(segment, QuadraticBezier) else list(segment.as_cubic_curves()))
            for curve in curves:
                out.append("C" + " ".join(number(v) for v in (
                    curve.control1.x - shift, curve.control1.y, curve.control2.x - shift, curve.control2.y,
                    curve.end.x - shift, curve.end.y)))
    return "".join(out)


def swift(name: str, figure: dict[str, list[str]], shift: float) -> list[str]:
    lines = [f"    static let {name}: [String: [String]] = ["]
    for slug in sorted(figure):
        lines.append(f'        "{slug}": [')
        lines += [f'            "{absolute(d, shift)}",' for d in figure[slug]]
        lines.append("        ],")
    lines.append("    ]")
    return lines


def main() -> int:
    front, back = parts(fetch("bodyFront")), parts(fetch("bodyBack"))
    body = [
        "// Generated by apps/apple/scripts/body-map.py; do not edit by hand.",
        f"// The figures are {REPOSITORY}'s male front and back at {COMMIT},",
        f"// {LICENSE}: permission is granted, free of charge, to deal in the",
        "// software without restriction, provided this notice is kept. Paths are",
        "// absolute M, L, C and Z in one 724 x 1448 box per figure.",
        "",
        "enum BodyMapShapes {",
        "    static let size = (width: 724.0, height: 1448.0)",
        "",
        *swift("front", front, 0),
        "",
        *swift("back", back, WIDTH),
        "}",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.relative_to(APPLE)}: front {sorted(front)}, back {sorted(back)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
