package dev.reamde.substrate.gradle

import com.android.build.api.variant.AndroidComponentsExtension
import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.kotlin.dsl.register

/**
 * An app's accent as resources: its app.json's `accent` written as `substrate_accent` and its text tone, `accent.text`, as `substrate_accent_text`, in
 * `values/` and `values-night/`, a generated res folder of every variant. kit-ui declares both with Substrate's blue, and an app's resources win the merge over
 * a library's, so `KitTheme` draws each app in its own colours with no code of the app's. A module with no app.json beside its folder (the kit's Gallery,
 * bridge-check) keeps kit-ui's.
 */
internal fun Project.generateAppAccent() {
    val appJSON = layout.projectDirectory.file("../app.json")
    if (!appJSON.asFile.exists()) return
    val task =
        tasks.register<AppAccent>("substrateAppAccent") {
            this.appJSON.set(appJSON)
            output.set(layout.buildDirectory.dir("generated/substrate/accent"))
        }
    extensions.getByType(AndroidComponentsExtension::class.java).onVariants { variant ->
        variant.sources.res?.addGeneratedSourceDirectory(task, AppAccent::output)
    }
}

/** Writes app.json's `accent` and its text tone as the two colours, light and night; app.json without both fails the build by name. */
abstract class AppAccent : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val appJSON: RegularFileProperty

    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun write() {
        val path = appJSON.get().asFile
        val accent = (JsonSlurper().parse(path) as? Map<*, *>)?.get("accent") as? Map<*, *>
        val text = accent?.get("text") as? Map<*, *>
        val hex = Regex("#[0-9A-Fa-f]{6}")
        val colours = listOf(accent?.get("light"), accent?.get("dark"), text?.get("light"), text?.get("dark")).map { it as? String }
        if (colours.any { it == null || !hex.matches(it) }) {
            throw GradleException(
                "$path names no accent {\"light\": \"#RRGGBB\", \"dark\": \"#RRGGBB\", \"text\": {\"light\": \"#RRGGBB\", \"dark\": \"#RRGGBB\"}}, which an app on Android is drawn in"
            )
        }
        val (light, dark, textLight, textDark) = colours.map { it!!.uppercase() }
        val out = output.get().asFile
        out.deleteRecursively()
        for ((folder, values) in listOf("values" to (light to textLight), "values-night" to (dark to textDark))) {
            val dir = out.resolve(folder).apply { mkdirs() }
            dir.resolve("substrate_accent.xml")
                .writeText(
                    """
                    |<?xml version="1.0" encoding="utf-8"?>
                    |<!-- Generated by build-logic's AppAccent from app.json; do not edit. -->
                    |<resources>
                    |    <color name="substrate_accent">${values.first}</color>
                    |    <color name="substrate_accent_text">${values.second}</color>
                    |</resources>
                    |"""
                        .trimMargin()
                )
        }
    }
}
