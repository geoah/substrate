/** An applet's launcher icon; a name off the list is the generic window. */
export function launcherIcon(name: string | undefined): LucideIcon {
  const key = (name ?? "").toLowerCase().replace(/[^a-z0-9]/g, "")
  return Object.hasOwn(LAUNCHER_ICONS, key) ? LAUNCHER_ICONS[key] : AppWindow
}

/** An Icon component's name: the catalog's word, else a launcher word, so
 * an agent that writes `book-open` in a screen is drawn too. */
export function iconByName(name: string): LucideIcon | undefined {
  const key = name.toLowerCase().replace(/[^a-z0-9]/g, "")
  return (
    catalogIcon(name) ??
    (Object.hasOwn(LAUNCHER_ICONS, key) ? LAUNCHER_ICONS[key] : undefined)
  )
}
