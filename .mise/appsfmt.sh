#!/usr/bin/env bash
#
# The apps' formatters, behind `fmt:swift`, `fmt:kotlin` and their checks:
#
#   swift          swift-format every Swift file under apps/ in place
#   swift check    the same over a copy, failing with the diff where it differs
#   kotlin         ktfmt every Kotlin source and Gradle script under apps/
#   kotlin check   the same over a copy, failing with the diff where it differs
#
# The check IS the writer, run on a copy of the files and diffed, so it can
# never fail on something `mise run fmt` would not fix. Each formatter is
# configured once: swift-format by apps/.swift-format, passed by path to both
# halves, and run from the open-source Swift the task names (Xcode's
# swift-format is another version, with other output); ktfmt by build-logic's
# KtfmtConvention, the apps/gradle `:ktfmt` task, with the width and indent of
# apps/.editorconfig, which the copy carries along with the root's.
#
# The files are the ones git tracks or would (untracked and not ignored), so a
# build output (.build, build/) is never read. A file whose first line is
# `// Generated by …; do not edit` belongs to its generator, whose own check
# compares it byte for byte (android:generate:check, the kit's
# DesignTokensKotlinTests), so neither half touches it.
set -euo pipefail

root=$(git rev-parse --show-toplevel)
cd "$root"

die() {
  printf 'appsfmt: %s\n' "$*" >&2
  exit 1
}

language=${1:-}
mode=${2:-write}
case "$language" in
swift) patterns=('apps/*.swift') ;;
kotlin) patterns=('apps/*.kt' 'apps/*.kts') ;;
*) die "no language named '${language}'; use swift or kotlin" ;;
esac
case "$mode" in
write | check) ;;
*) die "no mode named '${mode}'; use check, or nothing to write" ;;
esac

files=()
while IFS= read -r -d '' file; do
  [[ -f $file ]] || continue
  if head -n 1 "$file" | grep -q '^// Generated by .*; do not edit'; then
    continue
  fi
  files+=("$file")
done < <(git ls-files -z --cached --others --exclude-standard -- "${patterns[@]}")
[[ ${#files[@]} -gt 0 ]] || die "no ${language} file under apps/; the pattern matched nothing"

# format <dir>: the language's formatter over every file, under <dir>, until
# a pass changes nothing. ktfmt is not idempotent everywhere (a lambda's
# `.fold` after a block body moves on its second pass), and a writer that
# stopped after one pass would leave a tree its own check refuses.
format() {
  local dir=$1 paths=() file before after pass
  for file in "${files[@]}"; do paths+=("$dir/$file"); done
  after=$(cat "${paths[@]}" | cksum)
  for pass in 1 2 3; do
    before=$after
    format_once
    after=$(cat "${paths[@]}" | cksum)
    [[ $after != "$before" ]] || return 0
  done
  die "the ${language} under ${dir} still changed on pass ${pass}; the formatter does not settle"
}

# format_once: one pass of the formatter over `paths`.
format_once() {
  case "$language" in
  swift)
    swift format format --in-place --parallel --configuration "$root/apps/.swift-format" "${paths[@]}"
    ;;
  kotlin)
    # Gradle splits --args at whitespace, so a path holding any would be
    # read as two files.
    for file in "${paths[@]}"; do
      [[ $file != *[[:space:]]* ]] || die "ktfmt cannot be handed a path with whitespace: ${file}"
    done
    (cd apps/gradle && ./gradlew --console=plain --quiet :ktfmt "--args=${paths[*]}")
    ;;
  esac
}

if [[ $mode == write ]]; then
  format "$root"
  exit 0
fi

copy=$(mktemp -d)
trap 'rm -rf "$copy"' EXIT
printf '%s\0' "${files[@]}" .editorconfig apps/.editorconfig | tar --null -T - -cf - | tar -xf - -C "$copy"
format "$copy"

status=0
for file in "${files[@]}"; do
  diff -u --label "a/$file" --label "b/$file" "$file" "$copy/$file" || status=1
done
[[ $status -eq 0 ]] || die "the ${language} above is unformatted; \`mise run fmt:${language}\` writes it"
