-- The allowance ledger (decision 0230, engine/operatorspend.go): one row per
-- call the operator, whoever runs the deployment, pays for on a repository's
-- behalf under the operator defaults file (SUBSTRATE_OPERATOR_DEFAULTS). A
-- call reserves its ceiling before it runs and settles to its reported cost
-- after; a row still open an hour after it was opened is settled at its
-- ceiling. The day's spend is the sum over the rows opened since 00:00 UTC,
-- each at its settled cost or, while open, its ceiling. `slot` is the
-- operator default the call spent through (llm, embeddings).
--
-- It is the operator's data, not the repository's: no changelog entry writes
-- it, so it is not a fold table, `repository rebuild` and an import leave it
-- as it is, and no export carries it. Costs are cents with a fraction,
-- because an embeddings batch costs a small part of one.
CREATE TABLE IF NOT EXISTS operator_spend_reservations (
    repository    text        NOT NULL DEFAULT current_setting('substrate.repository'),
    id            bigint      GENERATED BY DEFAULT AS IDENTITY,
    slot          text        NOT NULL,
    opened_at     timestamptz NOT NULL,
    ceiling_cents numeric     NOT NULL,
    settled_cents numeric,
    settled_at    timestamptz,
    PRIMARY KEY (repository, id)
);
-- The day's sum and the expiry both read a repository's rows by when they
-- opened.
CREATE INDEX IF NOT EXISTS operator_spend_reservations_opened_idx
    ON operator_spend_reservations (repository, opened_at);

-- Repository-scoped like every table a dataset writes, with 0011's row level
-- security: the `repository` column defaults to the connection's setting and
-- the policy holds each row to it.
ALTER TABLE operator_spend_reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE operator_spend_reservations FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS operator_spend_reservations_repository ON operator_spend_reservations;
CREATE POLICY operator_spend_reservations_repository ON operator_spend_reservations FOR ALL
    USING (repository = current_setting('substrate.repository', true))
    WITH CHECK (repository = current_setting('substrate.repository', true));

-- The grants 0001 gave `ON ALL TABLES` covered what existed then, so a later
-- table carries its own. The app role reserves, settles and prunes; erasing a
-- repository runs on the maint pool.
DO $$
DECLARE
    sch text := current_schema();
BEGIN
    IF to_regrole('substrate_app') IS NOT NULL THEN
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.operator_spend_reservations TO substrate_app', sch);
    END IF;
    IF to_regrole('substrate_maint') IS NOT NULL THEN
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.operator_spend_reservations TO substrate_maint', sch);
    END IF;
END $$;
