-- The observed index (decision 0160, engine/observedindex.go): tables the
-- fold derives from the rows of every kind that binds core's `observed`
-- trait, the way it derives `refs`. Each row is a function of one record's
-- properties and its kind's binding, of the points those produce, or of the
-- rollup rows those make, and of nothing else (no clock, no other record
-- beyond a metric's rollup tiers), so `repository rebuild` clears them and the
-- background re-derivation reproduces them from the records. `repository
-- verify` and the export never read them.
--
-- A reference (`metric`, `source`, `about`) is the target's record path,
-- `<kind>/<id>`. An absent `source`, `about`, `channel`, `statistic`, `code`
-- or `unit` is the empty string, so the columns can key a row. An absent UTC
-- offset is 0 with `offset_known` false, so a reader tells a value written
-- without an offset from one written at offset 0.
--
-- Every record id column sorts COLLATE "C", byte order: points at one
-- instant are ordered by record id, and the database's own collation (en_US
-- in the pgvector image) orders case and punctuation differently from Go's
-- string comparison, which internal/observed.Before and every reader in Go
-- use.

-- observed_streams: one row per stream, the private id every other table
-- keys by in place of the six text columns. The id is the engine's alone:
-- no record, changelog line, API answer or test expectation names it, and a
-- rebuild may hand a stream a different one. `max_extent_ms` is the longest
-- extent (first point to latest span end) of any record the stream has held:
-- a read of [lo, hi) finds every record whose points may meet it among those
-- starting in [lo - max_extent_ms, hi). It only grows, since a bound that is
-- too wide costs a read time and one too narrow costs it points.
CREATE TABLE IF NOT EXISTS observed_streams (
    repository     text        NOT NULL DEFAULT current_setting('substrate.repository'),
    id             bigint      GENERATED BY DEFAULT AS IDENTITY,
    metric         text        NOT NULL,
    kind           text        NOT NULL,
    source         text        NOT NULL DEFAULT '',
    about          text        NOT NULL DEFAULT '',
    channel        text        NOT NULL DEFAULT '',
    statistic      text        NOT NULL DEFAULT '',
    max_extent_ms  bigint      NOT NULL DEFAULT 0,
    PRIMARY KEY (repository, id),
    UNIQUE (repository, metric, kind, source, about, channel, statistic)
);

-- observed_segments: one row per observed record, never one per point. The
-- points stay in the record's own properties; a read takes the segments
-- that meet its range and derives their points again in Go (deriveObserved),
-- the way the fold derives them. `first_ts` and `last_ts` are the earliest
-- and the latest point's instant, `end_ts` the latest end of any span (at
-- least `last_ts`), `points` counts the points, nulls included, and
-- `available` those with a value or a code. `last_available` is the instant
-- of the newest available point, which the latest row is found by. A record
-- has one UTC offset (`utc_offset_min`, `offset_known`), and `codes` lists
-- the codes of its available points, '' for a number without one, so a read
-- learns what a whole record holds without deriving it. `fingerprint` is a
-- hash of everything the index reads from the record: a write that changes
-- none of it (a note, a title) derives nothing again.
CREATE TABLE IF NOT EXISTS observed_segments (
    repository     text        NOT NULL DEFAULT current_setting('substrate.repository'),
    kind           text        NOT NULL,
    record_id      text        COLLATE "C" NOT NULL,
    stream         bigint      NOT NULL,
    form           text        NOT NULL,
    first_ts       timestamptz NOT NULL,
    last_ts        timestamptz NOT NULL,
    end_ts         timestamptz NOT NULL,
    points         integer     NOT NULL,
    available      integer     NOT NULL,
    last_available timestamptz,
    utc_offset_min integer     NOT NULL,
    offset_known   boolean     NOT NULL,
    codes          text[]      NOT NULL,
    fingerprint    bytea       NOT NULL,
    PRIMARY KEY (repository, kind, record_id),
    CHECK (first_ts <= last_ts AND last_ts <= end_ts),
    CHECK ((last_available IS NULL) = (available = 0))
);
-- A stream's records by their first point: a range read, the point current
-- at a window's start, the latest row and a rollup recompute, each one index
-- range bounded by the stream's max_extent_ms.
CREATE INDEX IF NOT EXISTS observed_segments_stream_idx
    ON observed_segments (repository, stream, first_ts);

-- observed_rollups: one row per stream, form, tier, bucket and group, for
-- gauges, amounts and counters and never for summaries, computed by
-- internal/observed. `tier` is the bucket's width in seconds, one of the
-- widths the metric's `rollups` names (300, 900, 3600, 86400; absent means
-- 900, 3600 and 86400, an empty list none). A group is a code, a unit, the
-- delta flag, a UTC offset and whether the offset was recorded: the
-- statistics are in the row's own `unit`, so two units that share no base
-- never add. A bucket starts at a multiple of its width in the group's own
-- offset, or in UTC where the offset is unknown, so a 1-day row of a +02:00
-- group is a local day. The finest tier is computed from the points; each
-- coarser one from the next finer tier's rows (internal/observed.Compose),
-- or from the points where a finer row crosses its bucket's edge.
--
-- A read served from the rows answers what the raw points answer, so a row
-- keeps, beyond its statistics:
--
--   - `min_value` and `max_value`, the stored digits of the smallest and the
--     largest number, compared exactly, beside the float8 `min` and `max`.
--   - `first_record_id`, `first_ord`, `last_record_id` and `last_ord`, the
--     record id and index of the first and last point, so two rows whose
--     first (or last) points share an instant are ordered as the raw points
--     are.
--   - `span_end`, the latest end of an amount row's spans: its `covered_ms`
--     is the union of the spans, all inside [first_ts, span_end).
--   - `max_gap_ms`, `start_gap_ms` and `end_gap_ms`, the bucket's largest gap
--     between points and its gaps from its start to the first point and from
--     the last point to its end, every group and every null counted: what a
--     gauge's hold is cut by, and what a coarser row is composed from.
--
-- `increase` is null where the row holds no step (a counter's reading with
-- none before it): no answer, not a change of zero.
CREATE TABLE IF NOT EXISTS observed_rollups (
    repository     text        NOT NULL DEFAULT current_setting('substrate.repository'),
    stream         bigint      NOT NULL,
    form           text        NOT NULL,
    tier           integer     NOT NULL,
    bucket         timestamptz NOT NULL,
    code           text        NOT NULL,
    unit           text        NOT NULL,
    delta          boolean     NOT NULL,
    utc_offset_min integer     NOT NULL,
    offset_known   boolean     NOT NULL,
    n              bigint      NOT NULL,
    bounded        bigint      NOT NULL,
    sum            float8,
    min            float8,
    max            float8,
    min_value      numeric,
    max_value      numeric,
    mean           float8,
    m2             float8,
    first_ts       timestamptz,
    first_value    numeric,
    first_record_id text       COLLATE "C",
    first_ord      integer,
    last_ts        timestamptz,
    last_value     numeric,
    last_record_id text        COLLATE "C",
    last_ord       integer,
    covered_ms     bigint      NOT NULL,
    span_end       timestamptz,
    held_ms        bigint,
    twa_sum        float8,
    last_hold_ms   bigint,
    max_gap_ms     bigint      NOT NULL,
    start_gap_ms   bigint      NOT NULL,
    end_gap_ms     bigint      NOT NULL,
    increase       numeric,
    resets         integer,
    sin_sum        float8,
    cos_sum        float8,
    PRIMARY KEY (repository, stream, form, tier, bucket, code, unit, delta, utc_offset_min, offset_known),
    CHECK (tier IN (300, 900, 3600, 86400)),
    CHECK ((min IS NULL) = (min_value IS NULL) AND (max IS NULL) = (max_value IS NULL)),
    CHECK ((first_ts IS NULL) = (first_record_id IS NULL) AND (first_ts IS NULL) = (first_ord IS NULL)),
    CHECK ((last_ts IS NULL) = (last_record_id IS NULL) AND (last_ts IS NULL) = (last_ord IS NULL)),
    CHECK ((span_end IS NOT NULL) = (form = 'amount' AND n > 0)),
    CHECK (increase IS NULL OR form = 'counter')
);

-- observed_latest: one row per stream (a summary's statistic is part of the
-- stream), its newest available point, so the stream list and the current
-- value of each read one row. Ties at one instant go to the greater record
-- id, then the later point: the order the `last` reducer reads. `points`
-- counts the stream's available points.
CREATE TABLE IF NOT EXISTS observed_latest (
    repository     text        NOT NULL DEFAULT current_setting('substrate.repository'),
    stream         bigint      NOT NULL,
    ts             timestamptz NOT NULL,
    ts_end         timestamptz NOT NULL,
    value          numeric,
    code           text        NOT NULL,
    unit           text        NOT NULL,
    delta          boolean     NOT NULL,
    form           text        NOT NULL,
    comparator     text        NOT NULL,
    utc_offset_min integer     NOT NULL,
    offset_known   boolean     NOT NULL,
    record_id      text        COLLATE "C" NOT NULL,
    points         bigint      NOT NULL,
    PRIMARY KEY (repository, stream)
);

-- observed_index: which derivation rules (engine/observedindex.go
-- observedIndexVersion) the tables were derived under. An open whose binary
-- carries newer rules asks the background re-derivation for every row of
-- every observed kind and records its version here, as a rebuild and a boot
-- import do. No row reads as version 0.
CREATE TABLE IF NOT EXISTS observed_index (
    repository     text        NOT NULL DEFAULT current_setting('substrate.repository'),
    version        integer     NOT NULL,
    derived_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (repository)
);

-- Repository-scoped like every table a dataset writes, with 0011's row
-- level security: the `repository` column defaults to the connection's
