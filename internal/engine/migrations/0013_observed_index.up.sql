-- The grants 0001 gave `ON ALL TABLES` and `ON ALL SEQUENCES` covered what
-- existed then, so a later table, and the sequence behind observed_streams'
-- id, carry their own. The app role writes the index tables in the write's
-- transaction and rewrites its one observed_index row; erasing a repository
-- runs on the maint pool.
DO $$
DECLARE
    sch text := current_schema();
    t   text;
BEGIN
    FOREACH t IN ARRAY ARRAY['observed_streams', 'observed_segments', 'observed_rollups', 'observed_latest'] LOOP
        IF to_regrole('substrate_app') IS NOT NULL THEN
            EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.%I TO substrate_app', sch, t);
        END IF;
        IF to_regrole('substrate_maint') IS NOT NULL THEN
            EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.%I TO substrate_maint', sch, t);
        END IF;
    END LOOP;
    IF to_regrole('substrate_app') IS NOT NULL THEN
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON TABLE %I.observed_index TO substrate_app', sch);
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO substrate_app',
            pg_get_serial_sequence(format('%I.observed_streams', sch), 'id'));
    END IF;
    IF to_regrole('substrate_maint') IS NOT NULL THEN
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.observed_index TO substrate_maint', sch);
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO substrate_maint',
            pg_get_serial_sequence(format('%I.observed_streams', sch), 'id'));
    END IF;
END $$;

-- The background re-derivation (engine/reprojection.go) gains the observed
-- index as its third: a kind that starts or stops binding `observed`, whose
-- rows were derived under older rules or none (observed_index), or whose
-- repository was rebuilt or imported, has every row re-derived behind the
-- open, the rebuild or the apply that asked for it. `observed_metrics` narrows
-- the work to the rows of the named metrics, whose `rollups` changed; NULL is
-- every row.
ALTER TABLE index_reprojections ADD COLUMN IF NOT EXISTS observed boolean NOT NULL DEFAULT false;
ALTER TABLE index_reprojections ADD COLUMN IF NOT EXISTS observed_metrics text[];
